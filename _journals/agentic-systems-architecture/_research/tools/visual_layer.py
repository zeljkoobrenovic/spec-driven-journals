def folders_in_config():
    return list(SUBJECTS)


def icon(folder):
    out = ROOT / "posts" / folder / "assets" / "icons" / f"{folder}.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    return _gen(out, ICON_STYLE + SUBJECTS[folder] + ".", folder)


def logo(folder):
    post = ROOT / "posts" / folder / "index.md"
    meta, body = parse_front_matter(post.read_text(encoding="utf-8"))
    prompt = g.build_prompt(meta.get("title", ""), meta.get("excerpt", ""), body[:4000]) + LOGO_SUFFIX
    # The shared base prompt's style phrases leak into images as printed labels; restate them as plain wishes.
    prompt = prompt.replace(
        "Style should match a polished business explainer board with flat vector cartoon illustration, crisp outlines, and minimal shading. ",
        "Draw it as a clean flat cartoon diagram with crisp outlines and minimal shading. ",
    ).replace(
        "include lightweight UI fragments, messages, dashboards, operational artifacts, or support touchpoints where they help explain the stage. ",
        "Small screens, messages and records may appear where they help, labelled only with words about the topic. ",
    )
    out = post.parent / "assets" / "images" / folder / "logo.jpeg"
    out.parent.mkdir(parents=True, exist_ok=True)
    return _gen(out, prompt, folder)


def hero(_=None):
    prompt = (
        "Create a cover illustration for a book on architecting agentic AI systems: a calm harbour-like control "
        "scene where one bright, abstract spark-shaped component (the model) sits inside a sturdy architecture of "
        "connected blocks: gates, a logbook, a sealed sandbox box, a durable timeline track and a person reviewing "
        "an approval card. The architecture bounds the spark. Polished business explainer board, flat vector "
        "illustration, crisp outlines, minimal shading, disciplined blue, teal, green and orange accents, generous "
        "margins, wide 16:9. No text, no title." + LOGO_SUFFIX
    )
    return _gen(ROOT / "assets" / "images" / "journal-logo.jpeg", prompt, "hero")


def _gen(out, prompt, label):
    out.parent.mkdir(parents=True, exist_ok=True)
    err = ""
    for _ in range(3):
        try:
            out.write_bytes(g.call_gemini_image(os.environ["GEMINI_API_KEY"], prompt))
            return f"ok {label}"
        except Exception as e:  # noqa: BLE001
            err = str(e)[:100]
    return f"FAIL {label}: {err}"


def frontmatter():
    for folder in SUBJECTS:
        post = ROOT / "posts" / folder / "index.md"
        text = post.read_text(encoding="utf-8")
        head, sep, rest = text[4:].partition("\n---\n")
        lines = head.split("\n")
        keys = {ln.split(":", 1)[0] for ln in lines}
        add = []
        if "icon" not in keys and (post.parent / "assets/icons" / f"{folder}.png").exists():
            add.append(f'icon: "assets/icons/{folder}.png"')
        if "logo" not in keys and (post.parent / "assets/images" / folder / "logo.jpeg").exists():
            add.append(f'logo: "assets/images/{folder}/logo.jpeg"')
            if "logo_credit" not in keys:
                add.append(f'logo_credit: "{CREDIT}"')
        if add:
            post.write_text("---\n" + "\n".join(lines + add) + sep + rest, encoding="utf-8")
            print("updated", folder)


if __name__ == "__main__":
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == "frontmatter":
        frontmatter()
    elif cmd == "hero":
        print(hero())
    else:
        fn = {"icons": icon, "logos": logo}[cmd]
        with concurrent.futures.ThreadPoolExecutor(6) as ex:
            for r in ex.map(fn, args or folders_in_config()):
                print(r, flush=True)

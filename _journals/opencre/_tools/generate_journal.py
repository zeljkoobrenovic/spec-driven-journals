#!/usr/bin/env python3
"""Generate the OpenCRE journal from the cached OpenCRE export.

Reads every `_input/cres*.json` page (the `/rest/v1/all_cres` export,
`{data, page, total_pages}`), then writes:

- one post per CRE:       posts/cre/<id>/index.md        permalink cre-<id>
- one post per standard:  posts/standards/<slug>/index.md  permalink standard-<slug>
- config.yaml             sections follow the CRE tree

Generated folders are rewritten on every run. Hand-written posts
(posts/introduction/) are left alone and listed first in config.yaml.

Standard library only, like _wiring/build.py.

    python3 _journals/opencre/_tools/generate_journal.py
"""
import collections
import glob
import json
import re
import shutil
from pathlib import Path

JOURNAL = Path(__file__).resolve().parent.parent
INPUT = JOURNAL / "_input"
POSTS = JOURNAL / "posts"
OPENCRE = "https://opencre.org"
DATE = "2026-10-22"

# Display order of the five roots and how the big technical root is split.
SPLIT_ROOT = "636-660"  # Technical application security controls

LINK_KIND = {
    "Linked To": "curated",
    "Automatically linked to": "automatic",
}


# ---------- loading ----------

def load_cres():
    cres = {}
    for f in sorted(glob.glob(str(INPUT / "cres*.json"))):
        for cre in json.loads(Path(f).read_text(encoding="utf-8"))["data"]:
            cres[cre["id"]] = cre
    return cres


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def md_cell(s):
    """Make text safe inside a markdown table cell / link text."""
    return (s or "").replace("|", "/").replace("\n", " ").replace("[", "(").replace("]", ")").strip()


def natural_key(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s or "")]


def fm_value(s):
    return '"' + s.replace("\n", " ").strip() + '"'


class Model:
    def __init__(self, cres):
        self.cres = cres
        self.children = collections.defaultdict(list)
        self.parent = {}
        self.related = collections.defaultdict(list)
        # standard name -> list of (doc, cre_id, kind)
        self.standards = collections.defaultdict(list)
        self.doctype = {}
        for cid, cre in cres.items():
            for link in cre["links"]:
                doc, lt = link["document"], link["ltype"]
                if doc["doctype"] == "CRE":
                    if lt == "Contains":
                        self.children[cid].append(doc["id"])
                    elif lt == "Is Part Of":
                        self.parent[cid] = doc["id"]
                    else:
                        self.related[cid].append(doc["id"])
                else:
                    self.standards[doc["name"]].append((doc, cid, LINK_KIND.get(lt, lt.lower())))
                    self.doctype[doc["name"]] = doc["doctype"]
        for cid in self.children:
            self.children[cid].sort(key=lambda k: self.cres[k]["name"].lower())
        self.roots = sorted((c for c in cres if c not in self.parent),
                            key=lambda c: (c != SPLIT_ROOT, cres[c]["name"].lower()))

    def name(self, cid):
        return self.cres[cid]["name"]

    def path(self, cid):
        out = []
        while cid in self.parent:
            cid = self.parent[cid]
            out.append(cid)
        return list(reversed(out))

    def dfs(self, cid):
        yield cid
        for k in self.children[cid]:
            yield from self.dfs(k)

    def std_links(self, cid):
        """Standard/tool documents linked to one CRE, grouped by standard name."""
        groups = collections.defaultdict(list)
        for link in self.cres[cid]["links"]:
            doc = link["document"]
            if doc["doctype"] != "CRE":
                groups[doc["name"]].append((doc, LINK_KIND.get(link["ltype"], link["ltype"].lower())))
        return groups

    def subtree_standards(self, cid):
        names = set()
        for k in self.dfs(cid):
            names.update(self.std_links(k))
        return names


def std_slug(name):
    return "standard-" + slugify(name)


def cre_slug(cid):
    return "cre-" + cid


def doc_label(doc):
    sid, sec, sub = doc.get("sectionID") or "", doc.get("section") or "", doc.get("subsection") or ""
    if sub:
        sec = f"{sec}: {sub}" if sec else sub
    return md_cell(sid), md_cell(sec)


def doc_link(text, doc):
    href = doc.get("hyperlink")
    return f"[{text}]({href})" if href and text else text


# ---------- visuals ----------

LOGO_CREDIT = "Image generated by Google Gemini (gemini-3-pro-image-preview)"


def visual_fm(slug):
    """icon/logo front matter for images present in assets/ (see generate_visuals.py)."""
    out = []
    if (JOURNAL / "assets" / "icons" / f"{slug}.png").exists():
        out.append(f'icon: "assets/icons/{slug}.png"')
    if (JOURNAL / "assets" / "images" / slug / "logo.jpeg").exists():
        out += [f'logo: "assets/images/{slug}/logo.jpeg"', f'logo_credit: "{LOGO_CREDIT}"']
    return out


# ---------- CRE pages ----------

def mermaid_block(m, cid):
    seen = set()

    def node(k):
        nid = "n" + k.replace("-", "")
        if nid in seen:
            return nid
        seen.add(nid)
        label = m.name(k).replace('"', "'")
        if len(label) > 48:
            label = label[:45].rstrip() + "…"
        return f'{nid}["{label}"]'
    lines = ["graph LR"]
    if cid in m.parent:
        lines.append(f"  {node(m.parent[cid])} --> {node(cid)}")
    for k in m.children[cid][:16]:
        lines.append(f"  {node(cid)} --> {node(k)}")
    if len(m.children[cid]) > 16:
        lines.append(f'  {node(cid)} --> more{cid.replace("-", "")}["… {len(m.children[cid]) - 16} more"]')
    lines.append(f"  style n{cid.replace('-', '')} stroke-width:3px")
    return "---begin mermaid---\n" + "\n".join(lines) + "\n---end mermaid---"


def cre_page(m, cid):
    cre = m.cres[cid]
    name = cre["name"]
    path = m.path(cid)
    kids = m.children[cid]
    related = sorted(set(m.related[cid]), key=lambda k: m.name(k).lower())
    groups = m.std_links(cid)
    std_names = sorted(groups, key=str.lower)
    n_maps = sum(len(v) for v in groups.values())

    where = " › ".join(m.name(p) for p in path) or "a top-level CRE"
    excerpt_bits = [f"CRE {cid}", f"in {where}" if path else "top-level area"]
    if kids:
        excerpt_bits.append(f"{len(kids)} sub-requirement{'s' if len(kids) != 1 else ''}")
    if n_maps:
        excerpt_bits.append(f"{n_maps} mapping{'s' if n_maps != 1 else ''} to {len(std_names)} standard{'s' if len(std_names) != 1 else ''} and tool{'s' if len(std_names) != 1 else ''}")
    excerpt = " · ".join(excerpt_bits) + "."

    fm = [
        "---",
        f'id: "CRE-{cid}"',
        f"title: {fm_value(name)}",
        f"date: {DATE}",
        "author: OpenCRE (opencre.org)",
        f"permalink: {cre_slug(cid)}",
        f"excerpt: {fm_value(excerpt)}",
        f"tags: {', '.join(std_names)}",
    ] + visual_fm(cre_slug(cid)) + ["---"]
    body = []

    summary = [f"> **CRE**: [{cid}]({OPENCRE}/cre/{cid})", ">"]
    if path:
        summary.append("> **Part of**: " + " › ".join(f"[[{cre_slug(p)}]]" for p in path))
    else:
        summary.append("> **Part of**: top level of the OpenCRE catalogue")
    if std_names:
        summary += [">", "> **Maps to**: " + ", ".join(f"[[{std_slug(s)}]]" for s in std_names)]
    body += summary + [""]

    if kids or cid in m.parent:
        if len(kids) >= 3:
            body += ["## Where It Sits", "", mermaid_block(m, cid), ""]
    if kids:
        body += ["## Contains", ""]
        for k in kids:
            sub = len(list(m.dfs(k))) - 1
            note = f" — {sub} more below" if sub else ""
            body.append(f"- [[{cre_slug(k)}]]{note}")
        body.append("")
    if related:
        body += ["## Related CREs", ""]
        body += [f"- [[{cre_slug(k)}]]" for k in related]
        body.append("")

    if std_names:
        body += ["## Mapped Standards and Tools", "",
                 "Each row is a section of an external standard or tool that OpenCRE links to this requirement. "
                 "*Curated* links were set by the OpenCRE editors; *automatic* links were derived by OpenCRE "
                 "(for example through CWE and CAPEC).", ""]
        for s in std_names:
            rows = sorted(groups[s], key=lambda r: (r[1] != "curated", natural_key(r[0].get("sectionID") or r[0].get("section"))))
            body += [f"### {s}", "", "| ID | Section | Link |", "| --- | --- | --- |"]
            for doc, kind in rows:
                sid, sec = doc_label(doc)
                if not sec and not sid:
                    sec = md_cell(doc.get("tooltype") or doc["name"])
                if sid:
                    sid = doc_link(sid, doc)
                else:
                    sec = doc_link(sec, doc)
                body.append(f"| {sid} | {sec} | {kind} |")
            body += ["", f"More: [[{std_slug(s)}]]", ""]
    else:
        body += ["## Mapped Standards and Tools", "",
                 "OpenCRE has no direct standard links on this requirement; see the requirements it contains.", ""]

    body += ["## Source", "",
             f"Generated from the OpenCRE catalogue entry [{cid}]({OPENCRE}/cre/{cid}). "
             "OpenCRE is maintained by the OpenCRE project; see [opencre.org](https://opencre.org) for the live data.", ""]
    return "\n".join(fm) + "\n" + "\n".join(body)


# ---------- standard pages ----------

def standard_page(m, sname):
    entries = m.standards[sname]
    by_section = collections.OrderedDict()
    for doc, cid, kind in entries:
        key = (doc.get("sectionID") or "", doc.get("section") or "", doc.get("subsection") or "")
        slot = by_section.setdefault(key, {"doc": doc, "cres": {}})
        # keep the strongest link kind per CRE
        if slot["cres"].get(cid) != "curated":
            slot["cres"][cid] = kind
    sections = sorted(by_section.items(), key=lambda kv: (natural_key(kv[0][0]), kv[0][1].lower()))
    cre_ids = {cid for _d, cid, _k in entries}
    curated = sum(1 for _d, _c, k in entries if k == "curated")
    is_tool = m.doctype[sname] == "Tool"
    kind_word = "tool" if is_tool else "standard"

    # which top-level areas this standard touches
    areas = collections.Counter(m.path(c)[0] if m.path(c) else c for c in cre_ids)

    excerpt = (f"{'Tool' if is_tool else 'Standard'} · {len(sections)} section{'s' if len(sections) != 1 else ''} "
               f"mapped to {len(cre_ids)} CRE{'s' if len(cre_ids) != 1 else ''} "
               f"({curated} curated, {len(entries) - curated} automatic links).")
    fm = [
        "---",
        f'id: "STD-{slugify(sname).upper()}"',
        f"title: {fm_value(sname)}",
        f"date: {DATE}",
        "author: OpenCRE (opencre.org)",
        f"permalink: {std_slug(sname)}",
        f"excerpt: {fm_value(excerpt)}",
        f"tags: {kind_word}, mapping",
        "---",
    ]
    body = [
        f"> **{kind_word.capitalize()}**: {sname}",
        ">",
        f"> **Coverage**: {len(sections)} sections linked to {len(cre_ids)} CREs — "
        f"{curated} curated and {len(entries) - curated} automatic links.",
        "",
        "## Where It Lands in the CRE Tree",
        "",
        "| Top-level area | CREs |",
        "| --- | --- |",
    ]
    for root, n in sorted(areas.items(), key=lambda kv: -kv[1]):
        body.append(f"| [[{cre_slug(root)}]] | {n} |")
    body += ["", "## Sections and Their CREs", "",
             f"Each row is one section of {sname} and the common requirements OpenCRE links it to. "
             "Links marked *(auto)* were derived automatically.", "",
             "| ID | Section | CREs |", "| --- | --- | --- |"]
    for (_sid, _sec, _sub), slot in sections:
        doc = slot["doc"]
        sid, sec = doc_label(doc)
        if not sec and not sid:
            sec = md_cell(doc.get("tooltype") or sname)
        if sid:
            sid = doc_link(sid, doc)
        else:
            sec = doc_link(sec, doc)
        cres = sorted(slot["cres"].items(), key=lambda kv: (kv[1] != "curated", m.name(kv[0]).lower()))
        links = "<br>".join(f"[[{cre_slug(c)}]]" + (" *(auto)*" if k != "curated" else "") for c, k in cres)
        body.append(f"| {sid} | {sec} | {links} |")
    body += ["", "## Source", "",
             f"Generated from the OpenCRE catalogue. Browse {sname} on "
             f"[opencre.org]({OPENCRE}/node/{'tool' if is_tool else 'standard'}/{sname.replace(' ', '%20')}).", ""]
    return "\n".join(fm) + "\n" + "\n".join(body)


# ---------- writing ----------

def write_post(rel_dir, text):
    d = POSTS / rel_dir
    d.mkdir(parents=True, exist_ok=True)
    (d / "index.md").write_text(text, encoding="utf-8")
    return f"{rel_dir}/index.md"


def yaml_str(s):
    return '"' + s.replace('"', "'") + '"'


def main():
    m = Model(load_cres())
    for gen in ("cre", "standards"):
        if (POSTS / gen).exists():
            shutil.rmtree(POSTS / gen)

    sections = []  # (title, description, [rel paths])
    intro = []
    if (POSTS / "introduction" / "index.md").exists():
        intro.append("introduction/index.md")
    root_pages = [write_post(f"cre/{r}", cre_page(m, r)) for r in m.roots]
    sections.append(("Start Here",
                     "What OpenCRE is, how this journal is generated from it, and the five top-level areas of the catalogue.",
                     intro + root_pages))

    def area_section(title, top, include_top):
        ids = list(m.dfs(top)) if include_top else [k for c in m.children[top] for k in m.dfs(c)]
        rels = [write_post(f"cre/{k}", cre_page(m, k)) for k in ids]
        n_std = len(m.subtree_standards(top))
        desc = (f"{len(ids)} common requirements under {m.name(top)} (CRE {top}), "
                f"in tree order, mapped across {n_std} standards and tools.")
        sections.append((title, desc, rels))

    for root in m.roots:
        if root == SPLIT_ROOT:
            for child in m.children[root]:
                area_section(f"{m.name(root)}: {m.name(child)}", child, include_top=True)
        else:
            area_section(m.name(root), root, include_top=False)

    std_order = sorted(m.standards, key=lambda s: (m.doctype[s] == "Tool", s.lower()))
    std_rels = [write_post(f"standards/{slugify(s)}", standard_page(m, s)) for s in std_order]
    sections.append(("Standards and Tools",
                     "The reverse view: each external standard or tool, its sections, and the CREs they map to.",
                     std_rels))

    lines = [
        "title: OpenCRE Atlas",
        "description: A browsable map of the [OpenCRE](https://opencre.org) Common Requirement Enumeration — "
        f"{len(m.cres)} security requirements in one tree, each linked to the sections of ASVS, CWE, CAPEC, NIST, ISO 27001, "
        "PCI DSS, SAMM, DSOMM and other standards and tools that say the same thing. Generated from the OpenCRE export.",
        "",
        "sections:",
    ]
    for title, desc, rels in sections:
        lines += [f"  - title: {yaml_str(title)}", f"    description: {yaml_str(desc)}", "    posts:"]
        lines += [f"      - {r}" for r in rels]
        lines.append("")
    (JOURNAL / "config.yaml").write_text("\n".join(lines), encoding="utf-8")

    total = sum(len(r) for _t, _d, r in sections)
    print(f"[opencre] {len(m.cres)} CREs, {len(m.standards)} standards/tools, "
          f"{len(sections)} sections, {total} posts")


if __name__ == "__main__":
    main()

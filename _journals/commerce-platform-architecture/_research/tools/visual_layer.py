def folders_in_config():
    return list(SUBJECTS)


def icon(folder):
    out = ROOT / "posts" / folder / "assets" / "icons" / f"{folder}.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    return _gen(out, ICON_STYLE + SUBJECTS[folder] + ".", folder)


def logo(folder):
    post = ROOT / "posts" / folder / "index.md"
    prompt = (
        "Create a wide 16:9 header illustration for a chapter of a book on commerce platform architecture: "
        + SCENES[folder]
        + ". Draw it as a clean flat cartoon scene with crisp outlines and minimal shading, light background, "
        "disciplined blue, teal, green and orange accents, generous margins. No title, headline, banner or caption anywhere, especially not at the top and never the words commerce platform architecture; the only words in the image are the quoted labels, each written once." + LOGO_SUFFIX
    )
    out = post.parent / "assets" / "images" / folder / "logo.jpeg"
    out.parent.mkdir(parents=True, exist_ok=True)
    return _gen(out, prompt, folder)


def hero(_=None):
    prompt = (
        "Create a cover illustration for a book on commerce platform architecture: one order travelling as a "
        "single parcel along a winding path through a small connected landscape of a storefront, a shopping cart, a "
        "payment terminal, a warehouse, a delivery van and a shop, with a return path looping back to the warehouse, "
        "under calm morning light. Polished business explainer board, flat vector illustration, crisp outlines, "
        "minimal shading, blues, teals, greens and warm orange, generous margins, wide 16:9. No text, no title, no "
        "labels, no signs, no words anywhere in the image." + LOGO_SUFFIX
    )
    return _gen(ROOT / "assets" / "images" / "journal-logo.jpeg", prompt, "hero")


def _gen(out, prompt, label):
    out.parent.mkdir(parents=True, exist_ok=True)
    err = ""
    for _ in range(3):
        try:
            out.write_bytes(g.call_gemini_image(os.environ["GEMINI_API_KEY"], prompt))
            return f"ok {label}"
        except Exception as e:  # noqa: BLE001
            err = str(e)[:100]
    return f"FAIL {label}: {err}"


def frontmatter():
    for folder in SUBJECTS:
        post = ROOT / "posts" / folder / "index.md"
        text = post.read_text(encoding="utf-8")
        head, sep, rest = text[4:].partition("\n---\n")
        lines = head.split("\n")
        keys = {ln.split(":", 1)[0] for ln in lines}
        add = []
        if "icon" not in keys and (post.parent / "assets/icons" / f"{folder}.png").exists():
            add.append(f'icon: "assets/icons/{folder}.png"')
        if "logo" not in keys and (post.parent / "assets/images" / folder / "logo.jpeg").exists():
            add.append(f'logo: "assets/images/{folder}/logo.jpeg"')
            if "logo_credit" not in keys:
                add.append(f'logo_credit: "{CREDIT}"')
        if add:
            post.write_text("---\n" + "\n".join(lines + add) + sep + rest, encoding="utf-8")
            print("updated", folder)


if __name__ == "__main__":
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == "frontmatter":
        frontmatter()
    elif cmd == "hero":
        print(hero())
    else:
        fn = {"icons": icon, "logos": logo}[cmd]
        with concurrent.futures.ThreadPoolExecutor(6) as ex:
            for r in ex.map(fn, args or folders_in_config()):
                print(r, flush=True)
